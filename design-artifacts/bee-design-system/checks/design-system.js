async (page) => {
  const apiCalls = []
  const observe = (request) => { if (new URL(request.url()).pathname.includes('/api/')) apiCalls.push(request.url()) }
  page.on('request', observe)
  try {
    await page.setViewportSize({width:1440,height:1000})
    await page.goto('http://127.0.0.1:4173/design-system.html#layar-siswa')
    await page.reload()
    const sample=page.locator('#layar-siswa')
    await sample.getByRole('button',{name:'Tambah siswa',exact:true}).click()
    let dialog=page.getByRole('dialog',{name:'Tambah siswa',exact:true})
    await dialog.locator('#siswa-name').fill('Contoh Uji Lokal')
    await dialog.locator('#siswa-spp').fill('1.250,50')
    await dialog.locator('#siswa-spp').press('Tab')
    await dialog.getByRole('button',{name:'Tambah siswa',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    await sample.locator('#siswa-search').fill('Contoh Uji Lokal')
    const created=await sample.locator('.directory-desktop tbody').innerText()
    if (!created.includes('Rp 1.250,5')) throw new Error('Decimal example amount changed')
    await sample.getByRole('button',{name:'Ubah Contoh Uji Lokal',exact:true}).first().click()
    dialog=page.getByRole('dialog',{name:'Ubah data siswa',exact:true})
    await dialog.locator('#siswa-name').fill('Contoh Uji Diperbarui')
    await dialog.getByRole('button',{name:'Simpan perubahan',exact:true}).click()
    await dialog.waitFor({state:'hidden'})
    await sample.locator('#siswa-search').fill('Contoh Uji Diperbarui')
    if (!await sample.getByRole('button',{name:'Ubah Contoh Uji Diperbarui',exact:true}).first().count()) throw new Error('Edited example missing')
    await sample.getByRole('button',{name:'Hapus Contoh Uji Diperbarui',exact:true}).first().click()
    await page.getByRole('alertdialog').getByRole('button',{name:'Hapus contoh',exact:true}).click()
    await page.getByRole('alertdialog').waitFor({state:'hidden'})
    if (!await sample.getByText('Tidak ada siswa yang cocok',{exact:true}).count()) throw new Error('Deleted example still visible')
    const billing=page.locator('#layar-tagihan')
    await billing.getByRole('button',{name:'Catat pembayaran Alya Putri Oktober 2026',exact:true}).click()
    const payment=page.getByRole('dialog',{name:'Catat pembayaran',exact:true})
    await payment.locator('#bukti-bayar').fill('CONTOH-BAYAR')
    await payment.getByRole('button',{name:'Isi seluruh sisa',exact:true}).click()
    await payment.locator('#tanggal-bayar').fill('31/02/2026')
    await payment.locator('#tanggal-bayar').press('Tab')
    await payment.getByRole('button',{name:'Simpan pembayaran',exact:true}).click()
    await payment.getByText('Periksa atau pilih ulang tanggal pembayaran.',{exact:true}).waitFor()
    await payment.locator('#tanggal-bayar').fill('16/10/2026')
    await payment.locator('#tanggal-bayar').press('Tab')
    await payment.getByRole('button',{name:'Simpan pembayaran',exact:true}).click()
    await payment.waitFor({state:'hidden'})
    const paid=billing.locator('.tagihan-desktop tbody tr').filter({hasText:'Alya Putri'})
    if(!await paid.getByText('Lunas',{exact:true}).count()) throw new Error('Demo payment did not settle the example')
    await billing.getByRole('button',{name:'Rincian tagihan Alya Putri Oktober 2026',exact:true}).click()
    await page.getByRole('menuitem',{name:'Riwayat pembayaran',exact:true}).click()
    const history=page.getByRole('dialog',{name:'Riwayat pembayaran',exact:true})
    await history.getByText('CONTOH-BAYAR',{exact:true}).waitFor()
    await history.getByRole('button',{name:'Tutup',exact:true}).click()
    const legacy=billing.locator('.tagihan-desktop tbody tr').filter({hasText:'Daffa Ramadhan'})
    if(await legacy.getByRole('button',{name:/Catat pembayaran/}).count()) throw new Error('Unknown example allows payment')
    await billing.getByRole('button',{name:'Rincian tagihan Daffa Ramadhan September 2026',exact:true}).click()
    await page.getByRole('menuitem',{name:'Lihat faktur',exact:true}).click()
    const invoice=page.getByRole('dialog',{name:'Faktur contoh',exact:true})
    await invoice.getByText('Perlu dicocokkan',{exact:true}).waitFor()
    if((await invoice.innerText()).includes('Dibayar: Rp 0')) throw new Error('Unknown demo invoice fabricated zero')
    await invoice.getByRole('button',{name:'Tutup contoh faktur',exact:true}).click()
    const activities=page.locator('#layar-kegiatan')
    if(await activities.getByRole('button',{name:'Buat kegiatan',exact:true}).count()) throw new Error('Teacher example has create control')
    await activities.getByRole('button',{name:'Catat realisasi Pekan membaca',exact:true}).click()
    const realization=page.getByRole('dialog',{name:'Catat realisasi',exact:true})
    await realization.locator('#realisasi-amount').fill('35,50')
    await realization.locator('#realisasi-description').fill('Realisasi fiktif terarah')
    await realization.locator('#realisasi-date').fill('31/02/2026')
    await realization.locator('#realisasi-date').press('Tab')
    await realization.getByRole('button',{name:'Catat realisasi',exact:true}).click()
    await realization.getByText('Periksa atau pilih ulang tanggal pengeluaran.',{exact:true}).waitFor()
    await realization.locator('#realisasi-date').fill('16/10/2026')
    await realization.locator('#realisasi-date').press('Tab')
    await realization.getByRole('button',{name:'Catat realisasi',exact:true}).click()
    await realization.waitFor({state:'hidden'})
    await activities.getByRole('button',{name:'Laporan Pekan membaca',exact:true}).click()
    const activityReport=page.getByRole('dialog',{name:'Laporan kegiatan',exact:true})
    await activityReport.getByText('Realisasi fiktif terarah',{exact:true}).waitFor()
    await activityReport.getByRole('button',{name:'Tutup',exact:true}).click()
    await activities.getByRole('button',{name:'Kepala sekolah',exact:true}).click()
    await activities.getByRole('button',{name:'Buat kegiatan',exact:true}).click()
    const activityForm=page.getByRole('dialog',{name:'Buat kegiatan',exact:true})
    await activityForm.locator('#activity-name').fill('Workshop contoh')
    await activityForm.locator('#activity-account').click()
    await page.getByRole('option',{name:'Beban kegiatan sekolah',exact:true}).click()
    await activityForm.locator('#activity-budget').fill('1050000,50')
    await activityForm.locator('#activity-start').fill('31/02/2026')
    await activityForm.locator('#activity-start').press('Tab')
    await activityForm.getByRole('button',{name:'Buat kegiatan',exact:true}).click()
    await activityForm.getByText('Tanggal yang diketik tidak valid. Periksa atau pilih ulang tanggal kegiatan.',{exact:true}).waitFor()
    await activityForm.locator('#activity-start').fill('16/10/2026')
    await activityForm.locator('#activity-start').press('Tab')
    await activityForm.getByRole('button',{name:'Buat kegiatan',exact:true}).click()
    await activityForm.waitFor({state:'hidden'})
    await activities.getByText('Workshop contoh',{exact:true}).first().waitFor()
    await activities.getByRole('button',{name:'Tindakan kegiatan Workshop contoh',exact:true}).click()
    await page.getByRole('menuitem',{name:'Hapus kegiatan',exact:true}).click()
    await page.getByRole('alertdialog').getByRole('button',{name:'Hapus contoh',exact:true}).click()
    await page.getByRole('alertdialog').waitFor({state:'hidden'})
    if(await activities.getByText('Workshop contoh',{exact:true}).count()) throw new Error('Deleted activity example remains')
    if (apiCalls.length) throw new Error('Design-system demo sent API requests')
    return {createEditDelete:'passed',decimal:'1250.50',billing:'payment, history and unknown invoice passed',activities:'teacher realization/report and principal create/delete passed',invalidManualDates:'payment, realization and optional activity dates blocked and corrected',apiCalls,scope:'in-memory fictional examples only'}
  } finally {
    page.off('request', observe)
    await page.reload()
    await page.locator('#layar-siswa').scrollIntoViewIfNeeded()
  }
}
