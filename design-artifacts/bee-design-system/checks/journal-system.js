async(page)=>{
  const apiCalls=[]
  const errors=[]
  const onError=error=>errors.push(error.message)
  page.on('pageerror',onError)
  await page.route('**/api/**',async route=>{apiCalls.push(route.request().url());await route.fulfill({status:405,json:{detail:'No API allowed in design-system review'}})})
  try{
    await page.goto('http://127.0.0.1:4173/design-system.html#layar-jurnal')
    await page.reload()
    await page.setViewportSize({width:1440,height:1000})
    const section=page.locator('#layar-jurnal')
    await section.getByText('1–7 dari 7 jurnal',{exact:true}).waitFor()
    await section.scrollIntoViewIfNeeded()
    await page.screenshot({path:'design-artifacts/bee-design-system/jurnal-desktop-06.png',animations:'disabled'})
    await section.getByRole('button',{name:'Periksa jurnal CONTOH-001',exact:true}).filter({visible:true}).click()
    const detail=page.getByRole('dialog',{name:'Rincian jurnal',exact:true})
    await detail.getByRole('button',{name:'Ubah draf',exact:true}).click()
    const form=page.getByRole('dialog',{name:'Ubah draf jurnal',exact:true})
    await form.locator('#journal-proof').fill('CONTOH-DESIMAL')
    await form.locator('#journal-date').fill('31/02/2026')
    await form.locator('#journal-date').press('Tab')
    await form.getByRole('button',{name:'Simpan draf',exact:true}).click()
    await form.getByText('Periksa atau pilih ulang tanggal jurnal yang valid.',{exact:true}).waitFor()
    await form.locator('#journal-date').fill('16/10/2026')
    await form.locator('#journal-date').press('Tab')
    for(const [selector,value] of [['#journal-debit-0','0,10'],['#journal-credit-1','0,30']]){await form.locator(selector).fill(value);await form.locator(selector).press('Tab')}
    await form.getByRole('button',{name:'Tambah baris akun',exact:true}).click()
    await form.locator('#journal-account-2').click()
    await page.getByRole('option',{name:'Beban kegiatan',exact:true}).click()
    await form.locator('#journal-debit-2').fill('0,20')
    await form.locator('#journal-debit-2').press('Tab')
    await form.getByText('Seimbang',{exact:true}).waitFor()
    await page.screenshot({path:'design-artifacts/bee-design-system/jurnal-form-desktop-06.png',animations:'disabled'})
    await form.getByRole('button',{name:'Simpan draf',exact:true}).click()
    await form.waitFor({state:'hidden'})
    await detail.getByText('CONTOH-DESIMAL',{exact:true}).waitFor()
    await detail.getByRole('button',{name:'Catat ke buku besar',exact:true}).click()
    const confirm=page.getByRole('dialog',{name:'Catat ke buku besar',exact:true})
    await confirm.getByRole('button',{name:'Catat ke buku besar',exact:true}).click()
    await confirm.waitFor({state:'hidden'})
    await section.getByRole('button',{name:'Periksa jurnal CONTOH-DESIMAL',exact:true}).filter({visible:true}).click()
    await detail.getByText('Tercatat',{exact:true}).waitFor()
    if(await detail.getByRole('button',{name:'Ubah draf',exact:true}).count())throw new Error('Posted journal can be edited')
    await detail.getByRole('button',{name:'Tutup rincian',exact:true}).click()
    await section.getByRole('button',{name:'Periksa jurnal CONTOH-004',exact:true}).filter({visible:true}).click()
    if(await detail.getByRole('group',{name:'Tindakan jurnal',exact:true}).count())throw new Error('Reconciliation row has actions')
    await detail.getByRole('button',{name:'Tutup rincian',exact:true}).click()
    await section.getByRole('button',{name:'Periksa jurnal CONTOH-002',exact:true}).filter({visible:true}).click()
    await detail.getByRole('button',{name:'Batalkan penerimaan',exact:true}).click()
    const cancel=page.getByRole('dialog',{name:'Batalkan penerimaan',exact:true})
    await cancel.getByRole('button',{name:'Batalkan penerimaan',exact:true}).click()
    await cancel.getByText('Isi alasan pembatalan penerimaan.',{exact:true}).waitFor()
    await cancel.locator('#journal-cancel-reason').fill('Bukti contoh keliru')
    await cancel.getByRole('button',{name:'Batalkan penerimaan',exact:true}).click()
    await cancel.waitFor({state:'hidden'})
    await section.locator('#journal-demo-role').click()
    await page.getByRole('option',{name:'Kepala sekolah',exact:true}).click()
    if(await section.getByRole('button',{name:'Buat jurnal contoh',exact:true}).count())throw new Error('Principal can create journal')
    await section.getByRole('button',{name:'Periksa jurnal CONTOH-006',exact:true}).filter({visible:true}).click()
    await detail.getByText(/Persetujuan harus dilakukan oleh pengguna lain/).waitFor()
    if(await detail.getByRole('button',{name:'Setujui dan catat',exact:true}).count())throw new Error('Principal can approve own journal')
    await detail.getByRole('button',{name:'Tutup rincian',exact:true}).click()
    await section.getByRole('button',{name:'Periksa jurnal CONTOH-003',exact:true}).filter({visible:true}).click()
    await detail.getByRole('button',{name:'Setujui dan catat',exact:true}).click()
    const approval=page.getByRole('dialog',{name:'Setujui dan catat',exact:true})
    await approval.getByRole('button',{name:'Setujui dan catat',exact:true}).click()
    await approval.waitFor({state:'hidden'})
    await section.getByRole('button',{name:'Periksa jurnal CONTOH-005',exact:true}).filter({visible:true}).click()
    await detail.getByRole('button',{name:'Buat jurnal pembalik',exact:true}).click()
    const reversal=page.getByRole('dialog',{name:'Buat jurnal pembalik',exact:true})
    await reversal.getByRole('button',{name:'Buat jurnal pembalik',exact:true}).click()
    await reversal.waitFor({state:'hidden'})
    await section.getByRole('button',{name:'Periksa jurnal REV-CONTOH-005',exact:true}).filter({visible:true}).waitFor()
    await page.setViewportSize({width:320,height:800})
    await section.scrollIntoViewIfNeeded()
    if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Mobile journal page overflow')
    await page.screenshot({path:'design-artifacts/bee-design-system/jurnal-mobile-06.png',animations:'disabled'})
    await section.getByRole('button',{name:'Periksa jurnal CONTOH-005',exact:true}).filter({visible:true}).click()
    if(await detail.evaluate(element=>element.scrollWidth>element.clientWidth))throw new Error('Mobile detail overflow')
    await page.screenshot({path:'design-artifacts/bee-design-system/jurnal-detail-mobile-06.png',animations:'disabled'})
    await detail.getByRole('button',{name:'Tutup rincian',exact:true}).click()
    await section.locator('#journal-demo-role').click()
    await page.getByRole('option',{name:'Finance',exact:true}).click()
    await section.getByRole('button',{name:'Buat jurnal contoh',exact:true}).click()
    const create=page.getByRole('dialog',{name:'Buat jurnal',exact:true})
    await create.getByRole('button',{name:'Simpan draf',exact:true}).click()
    await create.getByText('Isi nomor bukti transaksi.',{exact:true}).waitFor()
    if(await create.evaluate(element=>element.scrollWidth>element.clientWidth))throw new Error('Mobile journal form overflow')
    await page.screenshot({path:'design-artifacts/bee-design-system/jurnal-form-mobile-06.png',animations:'disabled'})
    await create.getByRole('button',{name:'Batal',exact:true}).click()
    await create.waitFor({state:'hidden'})
    if(apiCalls.length)throw new Error('Design-system sent API requests: '+apiCalls.join(','))
    if(errors.length)throw new Error(errors.join('\n'))
    return {ok:true,apiRequests:apiCalls.length,checks:['manual invalid date blocked','decimal 0.10+0.20=0.30','posted immutable','reconciliation blocked','cancellation reason required','own approval blocked','eligible approval','reversal preserved','320px page/detail/form'],errors}
  }finally{
    await page.unroute('**/api/**')
    page.off('pageerror',onError)
    await page.setViewportSize({width:1440,height:1000})
    await page.goto('http://127.0.0.1:4173/design-system.html#layar-jurnal')
    await page.reload()
  }
}
